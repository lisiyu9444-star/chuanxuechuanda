/** 常见的后缀，用于归一化用户输入 */
const NAME_SUFFIXES = [
  '特别行政区', '维吾尔自治区', '壮族自治区', '回族自治区', '自治区',
  '自治州', '自治县', '地区', '省', '市', '盟', '州', '区', '县',
]

/** 归一化：去空白并逐级剥离行政后缀，生成候选名（长名优先） */
function normalizeCandidates(input: string): string[] {
  const cleaned = input.replace(/\s+/g, '')
  const candidates = [cleaned]
  let current = cleaned
  for (let i = 0; i < 3; i++) {
    const suffix = NAME_SUFFIXES.find((s) => current.endsWith(s) && current.length > s.length)
    if (!suffix) break
    current = current.slice(0, -suffix.length)
    candidates.push(current)
  }
  return candidates
}

/** 城市名按长度降序，保证“海南州”先于“海南”命中，减少歧义 */
const SORTED_CITY_NAMES = Object.keys(CITY_LONGITUDE).sort((a, b) => b.length - a.length)
const SORTED_PROVINCE_NAMES = Object.keys(PROVINCE_LONGITUDE).sort((a, b) => b.length - a.length)

/**
 * 根据用户填写的出生城市解析东经经度。
 * 匹配顺序：精确（含去后缀）-> 城市包含 -> 省份兜底；均失败返回 undefined（调用方按不校正处理）。
 */
export function findLongitude(location?: string): number | undefined {
  if (!location || typeof location !== 'string') return undefined
  const candidates = normalizeCandidates(location)
  for (const name of candidates) {
    if (CITY_LONGITUDE[name] !== undefined) return CITY_LONGITUDE[name]
  }
  const cleaned = candidates[0]
  for (const name of SORTED_CITY_NAMES) {
    if (cleaned.includes(name)) return CITY_LONGITUDE[name]
  }
  for (const name of SORTED_PROVINCE_NAMES) {
    if (cleaned.includes(name)) return PROVINCE_LONGITUDE[name]
  }
  return undefined
}
